// Builds src/data/assets.json from this repo's rp-assets/ (copies of rosepetal-ui's images and
// videos): size, format, the playground files that use each one now and the rosepetal-ui files that
// reference it. Usage is computed from
// rosepetal-ui when it sits next to this repo (RP_UI to point elsewhere); otherwise the previous usage data is kept.
// Without rp-assets/ (it is not in git: see README.md) the list stays as it is.
// Run: node scripts/assets-manifest.mjs
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { basename, extname, join, relative } from 'node:path'

const LOCAL = 'rp-assets'
const RP = process.env.RP_UI || '../../rosepetal-ui'
const OUT = 'src/data/assets.json'
const MEDIA = /\.(png|jpe?g|gif|svg|webp|ico|mp4|webm)$/i
const CODE = /\.(vue|js|ts|css|scss|json|html)$/i

function walk(dir, filter, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name)
    if (name === 'node_modules')
      continue
    if (statSync(p).isDirectory())
      walk(p, filter, out)
    else if (filter.test(name))
      out.push(p)
  }
  return out
}

// Code without its comments: a file name mentioned in a comment is not a use.
const uncommented = text => text
  .replace(/<!--[\s\S]*?-->/g, '')
  .replace(/\/\*[\s\S]*?\*\//g, '')
  .replace(/(^|[^:'"`])\/\/.*$/gm, '$1')

// The playground's own code (where an asset is used now); the asset lists themselves don't count.
if (!existsSync(LOCAL)) {
  console.log(`No ${LOCAL}/: ${OUT} kept as it is.`)
  process.exit(0)
}

const OWN = walk('src', CODE)
  .filter(p => !/src[\\/]data[\\/]assets\.(json|ts)$/.test(p))
  .map(p => ({ path: p.replace(/\\/g, '/'), text: uncommented(readFileSync(p, 'utf8')) }))

const hasRp = existsSync(join(RP, 'src'))
const previous = existsSync(OUT) ? new Map(JSON.parse(readFileSync(OUT, 'utf8')).map(a => [a.url, a])) : new Map()
const code = hasRp
  ? [...walk(join(RP, 'src'), CODE), join(RP, 'index.html')].map(p => ({ path: relative(RP, p), text: readFileSync(p, 'utf8') }))
  : []

// src/assets/index.js maps '@/assets/…' paths to imports for the old require() calls: being listed
// there is not a real use, so it is reported apart.
const REGISTRY = 'src/assets/index.js'

// Folders whose files are picked by a template string (e.g. logos/${account}.jpg), so "no direct
// reference" does not mean unused.
const DYNAMIC = [/^src\/assets\/logos\//, /^src\/assets\/faker\//]

const assets = walk(LOCAL, MEDIA).map((p) => {
  const local = relative(LOCAL, p) // e.g. logos/rp-logo.png, public/favicon.ico
  const rel = local.startsWith('public/') ? local : `src/assets/${local}` // its path in rosepetal-ui
  const url = `rp-assets/${local}`
  const name = basename(p)
  const old = previous.get(url)
  const hits = hasRp ? code.filter(c => c.text.includes(name)).map(c => c.path) : null
  return {
    path: rel,
    url,
    name,
    folder: local.split('/')[0],
    format: extname(name).slice(1).toLowerCase().replace('jpeg', 'jpg'),
    bytes: statSync(p).size,
    // Files of this playground that use it (by its file name).
    usedHere: OWN.filter(c => c.text.includes(name)).map(c => c.path),
    // Files of rosepetal-ui that use it.
    usedIn: hits ? hits.filter(h => h !== REGISTRY) : (old?.usedIn ?? []),
    registered: hits ? hits.includes(REGISTRY) : !!old?.registered,
    dynamic: DYNAMIC.some(r => r.test(rel)),
    // Made here (e.g. generated by a script) and not yet copied to rosepetal-ui.
    isNew: hasRp ? !existsSync(join(RP, rel)) : !!old?.isNew,
  }
}).sort((a, b) => a.folder.localeCompare(b.folder) || a.name.localeCompare(b.name))

writeFileSync(OUT, `${JSON.stringify(assets, null, 2)}\n`)
const mb = assets.reduce((s, a) => s + a.bytes, 0) / 1e6
console.log(`${assets.length} assets, ${mb.toFixed(1)} MB → ${OUT}${hasRp ? '' : ' (usage kept: ../rosepetal-ui not found)'}`)
